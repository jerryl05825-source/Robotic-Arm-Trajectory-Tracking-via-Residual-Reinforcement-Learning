                              <li><i>down</i> to the <b>flower line</b>,</li>
                              <li>and <i>finish the circle</i>.</li>
                              <li>Draw <i>up</i> to the <b>sun line</b></li>
                              <li>and <i>down</i> to the <b>flower line.</b></li>
                           </ol>
